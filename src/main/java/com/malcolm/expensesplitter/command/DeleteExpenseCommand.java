package com.malcolm.expensesplitter.command;

import com.malcolm.expensesplitter.models.Expense;
import com.malcolm.expensesplitter.repositories.ExpenseRepository;

public class DeleteExpenseCommand implements Command {

    private final ExpenseRepository expenseRepository;
    private final Expense expense;

    public DeleteExpenseCommand(ExpenseRepository expenseRepository, Expense expense) {
        this.expenseRepository = expenseRepository;
        this.expense = expense;
    }

    @Override
    public void execute() {
        expenseRepository.delete(expense);
    }

    @Override
    public void undo() {
        // Re-saving the expense entity. If ID was autogenerated and cleared, we might need to be careful,
        // but since we are using UUIDs in this app, saving the detached entity might re-attach or re-create it.
        expenseRepository.save(expense);
    }
}
